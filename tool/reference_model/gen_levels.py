"""Generates and proves Sand Burst Magic's 100 campaign levels.

    cd tool/reference_model && python3 gen_levels.py

For every level in content.py it tries seeds until the bot (core.play_bot)
wins the level, then stores the seed, the settled starting board, the move
limit, the star thresholds and the bot's winning moves. The Dart tests
replay every stored solution with the Dart engine and check that it wins
within the limit, so every shipped level is proven winnable.

Writes
  lib/core/level_data.dart          the shipped levels (Dart, generated)
  tool/reference_model/levels.json  the same data with metadata
  docs/LEVELS.md                    summary table
"""
import json
import math
import os

from core import (KIND_NAMES, WON, Config, DEFAULT_WEIGHTS, GENTLE_WEIGHTS,
                  hash_string, layout_text, make_layout, new_game, place,
                  play_bot)
from content import LEVELS, SLACK, WORLDS

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ATTEMPTS = 60
MAX_BOT_MOVES = 90


def objectives_text(objs):
    out = []
    for o in objs:
        if o[0] == 'special':
            out.append(f'special:{o[1]}:{o[2]}')
        else:
            out.append(f'{o[0]}:{o[1]}')
    return '|'.join(out)


def pieces_text(table):
    return '|'.join(f'{k}:{p}' for k, p in sorted(table.items()))


def min_moves(n):
    return 2 if n <= 2 else 4 if n <= 8 else 6


def build_level(n, spec):
    world = spec['world']
    palette = WORLDS[world - 1][2]
    weights = GENTLE_WEIGHTS if spec['weights'] == 'gentle' else DEFAULT_WEIGHTS
    lock_rows = spec['layout']['lock_rows'] if spec['layout'] else 3
    quick = 0
    for attempt in range(ATTEMPTS):
        seed = hash_string(f'sbm-level-{n}-{attempt}')
        rows = None
        if spec['layout']:
            ly = spec['layout']
            board = make_layout(seed ^ 0x5EED5, ly['fill'], ly['density'],
                                palette, ly['obstacles'], ly['specials'],
                                ly['blocked'], ly['lock_rows'])
            rows = layout_text(board)
        cfg = Config(mode='level', seed=seed, layout=rows, lock_rows=lock_rows,
                     objectives=spec['objectives'], weights=weights,
                     palette=palette, specials=spec['pieces'],
                     allow_powerups=spec['power'])
        s, log = play_bot(cfg, max_moves=MAX_BOT_MOVES)
        if s.status != WON:
            continue
        if len(log) < min_moves(n):
            quick += 1
            continue
        par = len(log)
        limit = 0
        if spec['limit'] == 'auto':
            limit = math.ceil(par * SLACK[world - 1]) + 2
        three = max(par, math.ceil(par * 1.15))
        two = math.ceil(par * 1.6) + 2
        if limit:
            three = min(three, limit)
            two = min(two, limit)
        # Replay with the limit in force: must still win.
        cfg.move_limit = limit
        r = new_game(cfg)
        for m in log:
            assert place(r, cfg, *m) is not None, (n, m)
        assert r.status == WON, (n, r.status, r.reason)
        return dict(n=n, world=world, seed=seed, attempt=attempt, layout=rows,
                    lock_rows=lock_rows, objectives=spec['objectives'],
                    limit=limit, weights=spec['weights'], palette=palette,
                    pieces=spec['pieces'], power=spec['power'],
                    intro=spec['intro'], par=par, two=two, three=three,
                    score=s.score, solution=log)
    raise SystemExit(f'level {n}: no winning seed in {ATTEMPTS} attempts '
                     f'({quick} won too quickly)')


def encode_moves(log):
    return ''.join(f'{s}{r}{c}' for s, r, c in log)


def dart_file(levels):
    lines = [
        '// GENERATED by tool/reference_model/gen_levels.py. Do not edit by hand.',
        '//',
        '// One line per level, fields separated by ";":',
        '// world;objectives;moveLimit;weights;powerUps;pieces;seed;lockRows;',
        '// layout;par;twoStars;threeStars;intro;solution',
        '//',
        '// objectives: type:target or special:target:kind, joined by "|".',
        '// pieces: kind:percent of special sand in dealt pieces.',
        '// layout: 10 rows top to bottom joined by "/" (empty: no layout).',
        '// solution: the bot\'s winning moves, three digits each',
        '// (slot, row, col); replayed by test/core/levels_test.dart.',
        "part of 'levels.dart';",
        '',
        'const List<String> _levelLines = [',
    ]
    for e in levels:
        fields = [
            str(e['world']), objectives_text(e['objectives']), str(e['limit']),
            e['weights'], '1' if e['power'] else '0', pieces_text(e['pieces']),
            str(e['seed']), str(e['lock_rows']),
            '/'.join(e['layout']) if e['layout'] else '',
            str(e['par']), str(e['two']), str(e['three']), e['intro'] or '',
            encode_moves(e['solution']),
        ]
        line = ';'.join(fields)
        assert "'" not in line and '$' not in line
        lines.append(f"  '{line}',")
    lines.append('];')
    return '\n'.join(lines) + '\n'


def describe(o):
    if o[0] == 'rows':
        return f'clear {o[1]} rows'
    if o[0] == 'score':
        return f'{o[1]} points'
    if o[0] == 'multi':
        return f'{o[1]} multi-row clears'
    if o[0] == 'obstacles':
        return f'break {o[1]} obstacles'
    return f'clear {o[1]} {KIND_NAMES[o[2]]} sand'


def markdown(levels):
    out = ['# Campaign levels', '',
           'Generated by `tool/reference_model/gen_levels.py`. Every level was',
           'won by the bot (`core.play_bot`) when it was made; its moves are',
           'stored in `lib/core/level_data.dart` and replayed by',
           '`test/core/levels_test.dart`, so every level is proven winnable.',
           '', 'Move limit: the bot\'s moves x slack (1.8 in world 1 down to',
           '1.4 in world 6) + 2. Stars: 3 for at most par x 1.15 moves,',
           '2 for at most par x 1.6 + 2, 1 for any win.', '']
    for wi, (wid, name, _) in enumerate(WORLDS, start=1):
        out += [f'## World {wi}: {name}', '',
                '| Level | Goal | Move limit | Bot moves | New |',
                '| --- | --- | --- | --- | --- |']
        for e in levels:
            if e['world'] != wi:
                continue
            goal = ', '.join(describe(o) for o in e['objectives'])
            if not e['power']:
                goal += ' (no power-ups)'
            out.append(f"| {e['n']} | {goal} | {e['limit'] or '-'} | "
                       f"{e['par']} | {e['intro'] or ''} |")
        out.append('')
    return '\n'.join(out)


def main():
    levels = []
    for n, spec in enumerate(LEVELS, start=1):
        e = build_level(n, spec)
        levels.append(e)
        print(f"{n:3d} w{e['world']} attempt {e['attempt']:2d} par {e['par']:3d} "
              f"limit {e['limit']:3d} {objectives_text(e['objectives'])}")
    with open(os.path.join(ROOT, 'lib', 'core', 'level_data.dart'), 'w') as f:
        f.write(dart_file(levels))
    with open(os.path.join(os.path.dirname(__file__), 'levels.json'), 'w') as f:
        json.dump([{k: v for k, v in e.items()} for e in levels], f, indent=1)
    with open(os.path.join(ROOT, 'docs', 'LEVELS.md'), 'w') as f:
        f.write(markdown(levels))


if __name__ == '__main__':
    main()
